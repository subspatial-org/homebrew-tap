#!/bin/sh
# Rewrite Formula/subspatial.rb for a release on subspatial-org/data-cli,
# taking each bundle's checksum from that release's SHA256SUMS.
#   ./update-formula.sh 0.3.0-alpha.2
set -eu
version=${1:?usage: $0 VERSION}
version=${version#v}
base="https://github.com/subspatial-org/data-cli/releases/download/v$version"
sums=$(curl -fsSL "$base/SHA256SUMS")
sum() {
  s=$(printf '%s\n' "$sums" | awk -v f="subspatial-cli-$version-$1" '$2 == f { print $1 }')
  [ -n "$s" ] || { echo "SHA256SUMS has no subspatial-cli-$version-$1" >&2; exit 1; }
  printf '%s' "$s"
}
cat > Formula/subspatial.rb <<RUBY
# Generated by update-formula.sh from the v$version release's SHA256SUMS.
class Subspatial < Formula
  desc "Command-line client for subspatial (unsigned alpha pilot)"
  homepage "https://github.com/subspatial-org/data-cli"
  version "$version"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$base/subspatial-cli-$version-darwin-arm64.unsigned.zip"
      sha256 "$(sum darwin-arm64.unsigned.zip)"
    end
    on_intel do
      url "$base/subspatial-cli-$version-darwin-amd64.unsigned.zip"
      sha256 "$(sum darwin-amd64.unsigned.zip)"
    end
  end

  on_linux do
    on_arm do
      url "$base/subspatial-cli-$version-linux-arm64.unsigned.tar.gz"
      sha256 "$(sum linux-arm64.unsigned.tar.gz)"
    end
    on_intel do
      url "$base/subspatial-cli-$version-linux-amd64.unsigned.tar.gz"
      sha256 "$(sum linux-amd64.unsigned.tar.gz)"
    end
  end

  def install
    bin.install "subspatial", "subspatiald"
  end

  def caveats
    <<~EOS
      Sign in with:
        subspatial login --api https://app.subspatial.io
      You need a subspatial alpha account (by invitation).
    EOS
  end

  test do
    assert_match "subspatial #{version}", shell_output("#{bin}/subspatial version")
  end
end
RUBY
echo "Formula/subspatial.rb now installs $version"
